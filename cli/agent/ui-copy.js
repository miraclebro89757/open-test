function uiText(key, params) {
  const table = MESSAGES[uiLocale()] || MESSAGES['zh-CN'];
  let text = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : (MESSAGES.en[key] || key);
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value ?? ''));
    }
  }
  return text;
}

function recordingProduces(mode) {
  const keys = {
    'ui+api': ['record.produce.ui', 'record.produce.api', 'record.produce.har'],
    'ui-only': ['record.produce.ui'],
    'api-only': ['record.produce.api', 'record.produce.har'],
  }[mode] || [];
  return keys.map((item) => uiText(item));
}

function recordingConfirmMessage(mode, sandboxUrl) {
  const label = uiText(`record.mode.${mode}.label`);
  return [
    `**${uiText('record.mode')}**`,
    '',
    label,
    '',
    `**${uiText('record.willRecord')}**`,
    '',
    ...recordingProduces(mode).map((item) => `- ${item}`),
    '',
    `**${uiText('record.sandbox')}**`,
    '',
    String(sandboxUrl || ''),
    '',
    uiText('record.hint'),
  ].join('\n');
}

