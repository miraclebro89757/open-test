/**
 * Export rendered scripts to files
 */
async function exportScripts(scripts, outputDir) {
  await fs.mkdir(outputDir, { recursive: true });
  
  const pytestPath = path.join(outputDir, 'test_api.py');
  const envPath = path.join(outputDir, '.env.example');
  const readmePath = path.join(outputDir, 'README.md');
  
  await fs.writeFile(pytestPath, scripts.pytestScript, 'utf-8');
  await fs.writeFile(envPath, scripts.envExample, 'utf-8');
  await fs.writeFile(readmePath, scripts.readme, 'utf-8');
  
  console.log(`📄 Exported files:`);
  console.log(`   - ${pytestPath}`);
  console.log(`   - ${envPath}`);
  console.log(`   - ${readmePath}`);
}

/**
 * Main CLI entry point
 */
async function main() {
  const args = process.argv.slice(2);
  
  if (args.length < 2) {
    console.error(`Usage: node har-renderer.js <har-file> <analysis-json> [output-dir]`);
    process.exit(1);
  }
  
  const harPath = args[0];
  const analysisPath = args[1];
  const outputDir = args[2] || path.dirname(harPath);
  
  try {
    // Load analysis
    const analysisContent = await fs.readFile(analysisPath, 'utf-8');
    const analysis = JSON.parse(analysisContent);
    
    // Render scripts
    const scripts = await renderHARToPytest(harPath, analysis);
    
    // Export
    await exportScripts(scripts, outputDir);
    
    console.log('\n✅ HAR rendering complete!');
    console.log(`   Output: ${outputDir}`);
    
  } catch (error) {
    console.error(`❌ Rendering failed: ${error.message}`);
    process.exit(1);
  }
}

