/**
 * Generate main test function
 */
function generateTestFunction(testName, entries, analysis, includeAssertions) {
  const steps = entries.map((entry, idx) => 
    generateTestStep(entry, idx, analysis, includeAssertions)
  );
  
  return `def ${testName}(api_session):
    """
    API Test Scenario
    
    This test was auto-generated from a HAR recording.
    Variables are extracted from responses and injected into subsequent requests.
    
    Steps:
${steps.map((_, i) => `    ${i + 1}. ${getStepDescription(entries[i])}`).join('\n')}
    """
    
${steps.join('\n\n')}
    
    print("✅ All API requests completed successfully!")`;
}

/**
 * Get step description from entry
 */
function getStepDescription(entry) {
  const method = entry.request.method;
  const url = new URL(entry.request.url);
  const path = url.pathname;
  
  // Generate human-readable description
  if (method === 'POST' && path.includes('login')) return 'User login';
  if (method === 'POST' && path.includes('auth')) return 'Authenticate';
  if (method === 'GET' && path.includes('user')) return 'Get user profile';
  if (method === 'POST') return `Create resource at ${path}`;
  if (method === 'PUT' || method === 'PATCH') return `Update resource at ${path}`;
  if (method === 'DELETE') return `Delete resource at ${path}`;
  if (method === 'GET') return `Fetch data from ${path}`;
  
  return `${method} ${path}`;
}

/**
 * Generate single test step
 */
function generateTestStep(entry, index, analysis, includeAssertions) {
  const { request, response } = entry;
  const method = request.method.toLowerCase();
  const url = new URL(request.url);
  const path = url.pathname + url.search;
  
  // Extract headers
  const headers = extractHeaders(request.headers);
  
  // Extract body
  const body = extractRequestBody(request);
  
  // Find variables to extract from this response
  const varsToExtract = (analysis.variables || []).filter(v => 
    v.location && v.location.includes(`response[${index}]`)
  );
  
  // Find variables to inject into this request
  const dependencies = (analysis.dependencies || []).filter(d => d.to === index);
  
  let stepCode = `    # Step ${index + 1}: ${getStepDescription(entry)}\n`;
  stepCode += `    print(f"📤 Step ${index + 1}: ${method.toUpperCase()} {path}")\n`;
  
  // Inject variables from previous responses
  if (dependencies.length > 0) {
    stepCode += `    # Inject variables from previous responses\n`;
    dependencies.forEach(dep => {
      stepCode += `    # ${dep.variable} extracted from step ${dep.from}\n`;
    });
  }
  
  // Build request
  stepCode += `    response_${index} = api_session.${method}(\n`;
  stepCode += `        f"{BASE_URL}${path}",\n`;
  
  if (Object.keys(headers).length > 0) {
    stepCode += `        headers=${JSON.stringify(headers, null, 8).replace(/"/g, "'")},\n`;
  }
  
  if (body) {
    stepCode += `        json=${formatPythonDict(body)},\n`;
  }
  
  stepCode += `        timeout=TIMEOUT,\n`;
  stepCode += `        verify=VERIFY_SSL,\n`;
  stepCode += `    )\n`;
  
  // Assertions
  if (includeAssertions) {
    stepCode += `    \n`;
    stepCode += `    # Validate response\n`;
    stepCode += `    assert response_${index}.status_code == ${response.status}, f"Expected ${response.status}, got {response_${index}.status_code}"\n`;
    
    // Add content-type assertion if present
    const contentType = response.headers.find(h => 
      h.name.toLowerCase() === 'content-type'
    );
    if (contentType && contentType.value.includes('application/json')) {
      stepCode += `    assert "application/json" in response_${index}.headers["Content-Type"]\n`;
    }
  }
  
  // Extract variables from response
  if (varsToExtract.length > 0) {
    stepCode += `    \n`;
    stepCode += `    # Extract variables for later use\n`;
    varsToExtract.forEach(varDef => {
      const varName = varDef.name;
      const extractPath = extractJsonPath(varDef.location);
      stepCode += `    TEST_DATA["${varName}"] = response_${index}.json()${extractPath}\n`;
      stepCode += `    print(f"  ✓ Extracted ${varName}: {TEST_DATA['${varName}']}")\n`;
    });
  }
  
  return stepCode;
}

/**
 * Extract headers from request (filter out noise)
 */
function extractHeaders(headers) {
  const result = {};
  
  headers.forEach(h => {
    const name = h.name.toLowerCase();
    
    // Include important headers
    if (
      name === 'content-type' ||
      name === 'authorization' ||
      name === 'accept' ||
      name.startsWith('x-') ||
      name === 'cookie'
    ) {
      // Check if value contains variable placeholder
      result[h.name] = h.value;
    }
  });
  
  return result;
}

/**
 * Extract request body
 */
function extractRequestBody(request) {
  if (!request.postData || !request.postData.text) {
    return null;
  }
  
  try {
    return JSON.parse(request.postData.text);
  } catch (e) {
    // Not JSON, return as string
    return request.postData.text;
  }
}

/**
 * Extract JSON path from location string
 */
function extractJsonPath(location) {
  // Convert "response[0].body.token" to ["token"]
  const match = location.match(/\.body\.(.+)$/);
  if (match) {
    const path = match[1];
    const parts = path.split('.');
    return parts.map(p => `["${p}"]`).join('');
  }
  return '';
}

/**
 * Format JavaScript object as Python dict
 */
function formatPythonDict(obj) {
  return JSON.stringify(obj, null, 8)
    .replace(/true/g, 'True')
    .replace(/false/g, 'False')
    .replace(/null/g, 'None')
    .replace(/"/g, "'");
}

/**
 * Generate helper functions
 */
function generateHelperFunctions(analysis) {
  return `# Helper Functions

def extract_json_value(response: requests.Response, json_path: str) -> Any:
    """Extract value from JSON response using dot notation."""
    data = response.json()
    keys = json_path.split('.')
    
    for key in keys:
        if isinstance(data, dict):
            data = data.get(key)
        else:
            return None
    
    return data


def wait_for_async_operation(
    session: requests.Session,
    status_url: str,
    max_attempts: int = 10,
    delay: int = 2
) -> Dict[str, Any]:
    """Poll status endpoint until operation completes."""
    import time
    
    for attempt in range(max_attempts):
        response = session.get(status_url, timeout=TIMEOUT)
        data = response.json()
        
        if data.get("status") in ["completed", "success", "done"]:
            return data
        
        print(f"  ⏳ Waiting for operation... (attempt {attempt + 1}/{max_attempts})")
        time.sleep(delay)
    
    raise TimeoutError(f"Operation did not complete within {max_attempts * delay}s")`;
}

/**
 * Generate .env.example file
 */
function generateEnvExample(analysis) {
  const sensitiveVars = analysis.sensitiveData || [];
  
  let envContent = `# API Test Environment Variables
# Copy this file to .env and fill in actual values

# Base URL
API_BASE_URL=http://localhost:3000

# Timeout (seconds)
API_TIMEOUT=30

# SSL Verification
VERIFY_SSL=true

# Authentication
`;
  
  // Add sensitive variables
  const seenVars = new Set();
  sensitiveVars.forEach(field => {
    const varName = field.category.toUpperCase();
    if (!seenVars.has(varName)) {
      seenVars.add(varName);
      envContent += `${varName}=your_${field.category}_here\n`;
    }
  });
  
  if (seenVars.size === 0) {
    envContent += `# No sensitive variables detected\n`;
  }
  
  return envContent;
}

