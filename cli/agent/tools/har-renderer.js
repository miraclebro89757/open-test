#!/usr/bin/env node
/**
 * HAR Renderer - Convert HAR files to executable pytest scripts
 * 
 * Features:
 * 1. HAR → pytest conversion with requests library
 * 2. Variable extraction and environment variable management
 * 3. Pre/post cleanup hooks for test idempotency
 * 4. Request correlation and session management
 * 5. Assertion generation based on response validation
 * 
 * @module har-renderer
 */

const fs = require('fs').promises;
const path = require('path');

/**
 * Render HAR file to pytest script
 * 
 * @param {string} harPath - Path to HAR file
 * @param {object} analysis - HAR analysis result from har-analyzer
 * @param {object} options - Rendering options
 * @returns {Promise<object>} Rendered scripts
 */
async function renderHARToPytest(harPath, analysis, options = {}) {
  console.log(`🎨 Rendering HAR to pytest: ${harPath}`);
  
  const {
    testName = 'test_api_scenario',
    baseUrl = null,
    timeout = 30,
    includeCleanup = true,
    includeAssertions = true,
  } = options;
  
  // Load HAR
  const harContent = await fs.readFile(harPath, 'utf-8');
  const har = JSON.parse(harContent);
  const entries = har.log.entries;
  
  // Generate pytest script
  const scriptParts = [];
  
  // 1. Imports and setup
  scriptParts.push(generateImports());
  scriptParts.push(generateConstants(analysis, baseUrl));
  
  // 2. Fixture for session management
  scriptParts.push(generateSessionFixture());
  
  // 3. Setup/teardown hooks
  if (includeCleanup) {
    scriptParts.push(generateCleanupHooks(analysis));
  }
  
  // 4. Main test function
  scriptParts.push(generateTestFunction(
    testName,
    entries,
    analysis,
    includeAssertions
  ));
  
  // 5. Helper functions
  scriptParts.push(generateHelperFunctions(analysis));
  
  const pytestScript = scriptParts.join('\n\n');
  
  // Generate .env.example
  const envExample = generateEnvExample(analysis);
  
  // Generate README
  const readme = generateTestReadme(testName, analysis);
  
  console.log(`  ✓ Generated pytest script (${pytestScript.length} chars)`);
  
  return {
    pytestScript,
    envExample,
    readme,
  };
}

