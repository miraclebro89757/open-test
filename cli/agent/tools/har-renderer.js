/**
 * Detect base URL from endpoints
 */
function detectBaseUrl(endpoints) {
  if (endpoints.length === 0) return 'http://localhost:3000';
  
  // Parse first endpoint to extract base URL pattern
  const match = endpoints[0].match(/^(GET|POST|PUT|DELETE|PATCH)\s+(.+)$/);
  if (match) {
    const urlPath = match[2];
    // Return placeholder, actual URL will be in .env
    return 'http://localhost:3000';
  }
  
  return 'http://localhost:3000';
}

